int mode() {
    static const int m = [] {
        // Default: native (bit-identical; 2026-10-11 Eden 0.452 vs guest 0.439 ms per block in turn, and it can run
        // off the rotation, see LSWTCS_REVERBOFF). LSWTCS_REVERB=0 runs the guest code.
        const char* e = getenv("LSWTCS_REVERB");
        if (e && e[0] == '0') {
            const char* t = getenv("LSWTCS_REVERBTRACE");
            const char* c = getenv("LSWTCS_REVERBCHECK");
            if (t && t[0] == '1') return 3;
            return (c && c[0] == '1') ? 2 : 0;
        }
        const char* t = getenv("LSWTCS_REVERBTRACE");
        if (t && t[0] == '1') return 3;
        const char* c = getenv("LSWTCS_REVERBCHECK");
        return (c && c[0] == '1') ? 2 : 1;
    }();
    return m;
}

bool off_rotation() {
    static const bool on = [] { const char* e = getenv("LSWTCS_REVERBOFF"); return !(e && e[0] == '0'); }();
    return on;
}

uint64_t now_ns() {
    return uint64_t(std::chrono::duration_cast<std::chrono::nanoseconds>(std::chrono::steady_clock::now().time_since_epoch()).count());
}
uint64_t g_calls = 0, g_ns = 0, g_guest_ns = 0, g_mismatch = 0;
uint64_t g_off_move_ns = 0, g_off_dsp_ns = 0, g_off_back_ns = 0;   // LSWTCS_REVERBOFF: core move there, DSP, move back
alignas(128) thread_local uint8_t g_frame[kFrameSize];   // per thread: the guest stack frame

// ---- trace: which guest memory does the reverb touch? ----
std::set<uint32_t> g_rd, g_wr;
void trace_report(uint32_t state) {
    auto dump = [&](const char* what, const std::set<uint32_t>& pages) {
        char line[1600]; int len = 0;
        uint32_t lo = 0, prev = 0; bool open = false;
        for (uint32_t p : pages) {
            if (open && p == prev + 1) { prev = p; continue; }
            if (open && len < 1450) len += snprintf(line + len, sizeof line - len, " %08X-%08X(%+d)", lo << 8, (prev + 1) << 8, int32_t((lo << 8) - state));
            lo = prev = p; open = true;
        }
        if (open && len < 1450) len += snprintf(line + len, sizeof line - len, " %08X-%08X(%+d)", lo << 8, (prev + 1) << 8, int32_t((lo << 8) - state));
        dbg_ram("[REVERB] %s (256-byte pages, offset from state %08X):%s\n", what, state, line);
    };
    dump("reads", g_rd);
    dump("writes", g_wr);
}

// ---- check: shadow state + output copies ----
constexpr uint32_t kStateSize = 0x4BA98;   // from LSWTCS_REVERBTRACE (Eden 2026-10-09): state writes end at r3 + 0x4BA98
// The last words of the block (+0x4B9D4, +0x4B9DC, +0x4BA6C) are kept by the effect's wrapper, not by this function
// (a block counter and bookkeeping that change while the shadow cannot see them): compare the DSP part only.
constexpr uint32_t kDspStateSize = 0x4B9D0;
std::vector<uint8_t> g_shadow;
uint32_t g_shadow_for = 0;
std::vector<float> g_wav_in, g_wav_guest, g_wav_native;
uint32_t g_wav_blocks = 0;

void write_wav(const char* path, const std::vector<float>& s, int ch) {
    FILE* f = fopen(path, "wb");
    if (!f) return;
    const uint32_t data = uint32_t(s.size() * 4), rate = 48000;
    auto u32 = [&](uint32_t v) { fwrite(&v, 4, 1, f); };
    auto u16 = [&](uint16_t v) { fwrite(&v, 2, 1, f); };
    fwrite("RIFF", 1, 4, f); u32(36 + data); fwrite("WAVEfmt ", 1, 8, f); u32(16); u16(3); u16(uint16_t(ch));
    u32(rate); u32(rate * 4 * ch); u16(uint16_t(4 * ch)); u16(32); fwrite("data", 1, 4, f); u32(data);
    fwrite(s.data(), 4, s.size(), f);
    fclose(f);
}

float be_float(uint8_t* base, uint32_t a) { uint32_t v = PPC_LOAD_U32(a); float f; memcpy(&f, &v, 4); return f; }
