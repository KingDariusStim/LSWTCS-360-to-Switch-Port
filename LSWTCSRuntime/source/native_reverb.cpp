// Strong definition: replaces the recompiled sub_827E2208 (a weak alias).
PPC_FUNC(sub_827E2208) {
    const int m = mode();
    if (m == 0) {   // guest code, timed the same way for comparison
        const uint64_t t0 = now_ns();
        __imp__sub_827E2208(ctx, base);
        g_guest_ns += now_ns() - t0;
        if (++g_calls % 3000 == 0)
            dbg_ram("[REVERB] guest: %llu blocks, %.3f ms per block\n", (unsigned long long)g_calls, g_guest_ns / 1e6 / g_calls);
        return;
    }
    const uint32_t r3 = ctx.r3.u32, r4 = ctx.r4.u32, r5 = ctx.r5.u32, r6 = ctx.r6.u32, r7 = ctx.r7.u32;
    if (m == 1 || m == 3) {
        Env E{base, ctx.fpscr, g_frame};
        if (m == 3) { E.rd_pages = &g_rd; E.wr_pages = &g_wr; E.slow = true; }
        const uint64_t t0 = now_ns();
        if (m == 3) rv_827E2208<true>(E, kFrameSp, r3, r4, r5, r6, r7);
        else if (off_rotation()) {
            struct Job { Env* E; uint32_t r3, r4, r5, r6, r7; } job{&E, r3, r4, r5, r6, r7};
            lswtcs_gil_blocking_urgent([](void* p) {
                const Job& j = *static_cast<const Job*>(p);
                const uint64_t a = now_ns();
                lsw_offcore_begin();
                const uint64_t b = now_ns();
                rv_827E2208<false>(*j.E, kFrameSp, j.r3, j.r4, j.r5, j.r6, j.r7);
                const uint64_t c = now_ns();
                lsw_offcore_end();
                g_off_move_ns += b - a; g_off_dsp_ns += c - b; g_off_back_ns += now_ns() - c;
            }, &job);
        } else rv_827E2208<false>(E, kFrameSp, r3, r4, r5, r6, r7);
        g_ns += now_ns() - t0;
        ++g_calls;
        if (m == 3 && (g_calls == 200 || g_calls == 2000)) trace_report(r3);
        if (g_calls % 3000 == 0)
            dbg_ram("[REVERB] native: %llu blocks, %.3f ms per block (off rotation: move %.3f, dsp %.3f, move back %.3f)\n",
                    (unsigned long long)g_calls, g_ns / 1e6 / g_calls, g_off_move_ns / 1e6 / g_calls,
                    g_off_dsp_ns / 1e6 / g_calls, g_off_back_ns / 1e6 / g_calls);
        return;
    }
    // Check mode.
    const uint32_t out[4] = {PPC_LOAD_U32(r5 + 0), PPC_LOAD_U32(r5 + 4), PPC_LOAD_U32(r5 + 12), PPC_LOAD_U32(r5 + 16)};
    // The inputs the reverb really reads (sub_827E2208 entry: state+100 = 1 -> both chains from input 0, 2 -> both
    // from input 1, else input 0 and input 1).
    const uint32_t in_mode = PPC_LOAD_U32(r3 + 100);
    const uint32_t in[2] = {PPC_LOAD_U32(r4 + (in_mode == 2 ? 4 : 0)), PPC_LOAD_U32(r4 + (in_mode == 1 ? 0 : 4))};
    if (g_shadow_for != r3) {   // first call (or a new reverb instance): start the shadow from the real state
        g_shadow.assign(PPC_HOST(r3), PPC_HOST(r3) + kStateSize);
        g_shadow_for = r3;
        dbg_ram("[REVERB] check: shadow of state %08X (%u KB), outputs %08X %08X %08X %08X, inputs %08X %08X\n", r3,
                kStateSize / 1024, out[0], out[1], out[2], out[3], in[0], in[1]);
    }
    static std::vector<uint8_t> out_copy(4 * kBlock * 4);
    for (int c = 0; c < 4; ++c) memcpy(&out_copy[c * kBlock * 4], PPC_HOST(out[c]), kBlock * 4);   // in case it mixes in
    static const int wav_s = [] { const char* e = getenv("LSWTCS_REVERBWAV"); return e ? atoi(e) : 0; }();
    // LSWTCS_REVERBTEST=1 (with REVERBCHECK + REVERBWAV, Eden): the reverb gets silence in the title and hub, so from
    // block 2000 on a test signal is written into its input buffer for both the guest and the native run: an
    // impulse, a 200 ms noise burst at 0.5 s, a 200 Hz -> 4 kHz sine sweep from 1 s to 2 s, clicks every 0.75 s
    // from 3 s, silence after 5 s (the tail).
    static const bool test = [] { const char* e = getenv("LSWTCS_REVERBTEST"); return e && e[0] == '1'; }();
    static uint64_t test_sample = 0;
    if (test && g_calls >= 2000) {
        static uint32_t rng = 12345;
        for (uint32_t n = 0; n < kBlock; ++n, ++test_sample) {
            const double t = double(test_sample) / 48000.0;
            float x = 0;
            if (test_sample == 0) x = 1.0f;
            else if (t >= 0.5 && t < 0.7) { rng = rng * 1664525u + 1013904223u; x = 0.4f * (float(rng >> 8) / 8388608.0f - 1.0f); }
            else if (t >= 1.0 && t < 2.0) { const double f0 = 200, f1 = 4000, T = 1.0, tt = t - 1.0;
                                            x = 0.4f * float(std::sin(2 * M_PI * (f0 * tt + (f1 - f0) * tt * tt / (2 * T)))); }
            else if (t >= 3.0 && t < 5.0 && test_sample % 36000 == 0) x = 0.8f;
            uint32_t u; memcpy(&u, &x, 4); u = __builtin_bswap32(u);
            memcpy(PPC_HOST(in[0] + 4 * n), &u, 4);
            if (in[1] != in[0]) memcpy(PPC_HOST(in[1] + 4 * n), &u, 4);
        }
    }
    // Start recording at the first block with sound on the input (the reverb gets silence during boot / menus).
    static bool rec_started = false;
    if (wav_s > 0 && !rec_started) {
        float peak = 0;
        for (uint32_t n = 0; n < kBlock; ++n)
            for (int c = 0; c < 2; ++c) peak = std::fmax(peak, std::fabs(be_float(base, in[c] + 4 * n)));
        if (peak > 1e-3f && peak < 16.0f) {
            rec_started = true;
            dbg_ram("[REVERB] recording starts at block %llu (input mode %u, peak %g)\n", (unsigned long long)g_calls, in_mode, peak);
        }
    }
    const bool rec = rec_started && g_wav_blocks < uint32_t(wav_s) * 48000u / kBlock;
    if (rec)
        for (uint32_t n = 0; n < kBlock; ++n)
            for (int c = 0; c < 2; ++c) g_wav_in.push_back(be_float(base, in[c] + 4 * n));
    // Guest on the real state.
    const uint64_t t0 = now_ns();
    __imp__sub_827E2208(ctx, base);
    const uint64_t t1 = now_ns();
    // Native on the shadow, with the same instance LSWTCS_REVERB=1 runs (no redirects): the guest's results are set
    // aside, the shadow state (DSP part; the wrapper's words stay real) and the outputs as they were before the call
    // go into guest memory, the native code runs there, its results go back to the shadow / out_copy and the
    // guest's results are put back, so the game only ever sees the guest's output.
    static std::vector<uint8_t> guest_state(kStateSize), guest_out(4 * kBlock * 4);
    memcpy(guest_state.data(), PPC_HOST(r3), kStateSize);
    for (int c = 0; c < 4; ++c) memcpy(&guest_out[c * kBlock * 4], PPC_HOST(out[c]), kBlock * 4);
    memcpy(PPC_HOST(r3), g_shadow.data(), kDspStateSize);
    for (int c = 0; c < 4; ++c) memcpy(PPC_HOST(out[c]), &out_copy[c * kBlock * 4], kBlock * 4);
    Env E{base, ctx.fpscr, g_frame};
    const uint64_t t1n = now_ns();
    rv_827E2208<false>(E, kFrameSp, r3, r4, r5, r6, r7);
    const uint64_t t2 = now_ns();
    memcpy(g_shadow.data(), PPC_HOST(r3), kStateSize);
    for (int c = 0; c < 4; ++c) memcpy(&out_copy[c * kBlock * 4], PPC_HOST(out[c]), kBlock * 4);
    memcpy(PPC_HOST(r3), guest_state.data(), kStateSize);
    for (int c = 0; c < 4; ++c) memcpy(PPC_HOST(out[c]), &guest_out[c * kBlock * 4], kBlock * 4);
    g_guest_ns += t1 - t0;
    g_ns += t2 - t1n;
    ++g_calls;
    bool same = true;
    for (int c = 0; c < 4; ++c) same &= memcmp(&out_copy[c * kBlock * 4], PPC_HOST(out[c]), kBlock * 4) == 0;
    const bool state_check = g_calls % 64 == 0;
    bool state_same = true;
    if (state_check) state_same = memcmp(g_shadow.data(), PPC_HOST(r3), kDspStateSize) == 0;
    if (!same || !state_same) {
        ++g_mismatch;
        if (g_mismatch <= 20) {
            float maxd = 0;
            for (int c = 0; c < 4; ++c)
                for (uint32_t n = 0; n < kBlock; ++n) {
                    float g = be_float(base, out[c] + 4 * n), x;
                    uint32_t u; memcpy(&u, &out_copy[c * kBlock * 4 + 4 * n], 4); u = __builtin_bswap32(u); memcpy(&x, &u, 4);
                    maxd = std::fmax(maxd, std::fabs(g - x));
                }
            char where[400] = "";
            if (state_check && !state_same) {   // the first differing 32-bit words of the state (guest/native)
                int len = 0, shown = 0;
                for (uint32_t off = 0; off + 4 <= kDspStateSize && shown < 8; off += 4) {
                    uint32_t a, b;
                    memcpy(&a, &g_shadow[off], 4);
                    memcpy(&b, PPC_HOST(r3) + off, 4);
                    if (a != b) {
                        len += snprintf(where + len, sizeof where - len, " +%X:%08X/%08X", off, __builtin_bswap32(b), __builtin_bswap32(a));
                        ++shown;
                    }
                }
            }
            dbg_ram("[REVERB] MISMATCH block %llu: outputs %s (max |diff| %g), state %s%s\n", (unsigned long long)g_calls,
                    same ? "same" : "DIFF", maxd, state_check ? (state_same ? "same" : "DIFF (guest/native)") : "not checked", where);
        }
        // Resync so later blocks are compared from the same state again.
        memcpy(g_shadow.data(), PPC_HOST(r3), kStateSize);
    }
    if (rec) {
        for (uint32_t n = 0; n < kBlock; ++n)
            for (int c = 0; c < 4; ++c) {
                g_wav_guest.push_back(be_float(base, out[c] + 4 * n));
                uint32_t u; memcpy(&u, &out_copy[c * kBlock * 4 + 4 * n], 4); u = __builtin_bswap32(u);
                float x; memcpy(&x, &u, 4); g_wav_native.push_back(x);
            }
        if (++g_wav_blocks == uint32_t(wav_s) * 48000u / kBlock) {
            write_wav(LSW_WAV_DIR "reverb_input.wav", g_wav_in, 2);
            write_wav(LSW_WAV_DIR "reverb_guest.wav", g_wav_guest, 4);
            write_wav(LSW_WAV_DIR "reverb_native.wav", g_wav_native, 4);
            // Native impulse response from a copy of the current state: a unit impulse on both inputs, then 3 s
            // of silence (inputs and outputs redirected to host buffers).
            std::vector<uint8_t> st(g_shadow);
            std::vector<uint8_t> inb(2 * kBlock * 4, 0), outb(4 * kBlock * 4, 0);
            std::vector<float> ir;
            for (uint32_t blk = 0; blk < 3 * 48000 / kBlock; ++blk) {
                std::fill(inb.begin(), inb.end(), 0);
                if (blk == 0) { const uint32_t one = __builtin_bswap32(0x3F800000u); memcpy(&inb[0], &one, 4); memcpy(&inb[kBlock * 4], &one, 4); }
                std::fill(outb.begin(), outb.end(), 0);
                Redirect r2[7] = {{r3, r3 + kStateSize, st.data()}, {in[0], in[0] + kBlock * 4, &inb[0]},
                                  {in[1], in[1] + kBlock * 4, &inb[kBlock * 4]}};
                for (int c = 0; c < 4; ++c) r2[3 + c] = {out[c], out[c] + kBlock * 4, &outb[c * kBlock * 4]};
                Env E2{base, ctx.fpscr, g_frame, r2, 7};
                E2.slow = true;
                rv_827E2208<true>(E2, kFrameSp, r3, r4, r5, r6, r7);
                for (uint32_t n = 0; n < kBlock; ++n)
                    for (int c = 0; c < 4; ++c) {
                        uint32_t u; memcpy(&u, &outb[c * kBlock * 4 + 4 * n], 4); u = __builtin_bswap32(u);
                        float x; memcpy(&x, &u, 4); ir.push_back(x);
                    }
            }
            write_wav(LSW_WAV_DIR "reverb_native_ir.wav", ir, 4);
            dbg_ram("[REVERB] wrote %u s of reverb_input/guest/native.wav and reverb_native_ir.wav\n", unsigned(wav_s));
        }
    }
    if (g_calls % 1000 == 0)
        dbg_ram("[REVERB] check: %llu blocks, %llu mismatches; guest %.3f ms, native %.3f ms per block (x%.1f)\n",
                (unsigned long long)g_calls, (unsigned long long)g_mismatch, g_guest_ns / 1e6 / g_calls, g_ns / 1e6 / g_calls,
                g_ns ? double(g_guest_ns) / double(g_ns) : 0.0);
}
