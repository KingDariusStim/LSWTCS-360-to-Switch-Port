// Native replacement for the game's reverb DSP (guest sub_827E2208; the XAudio2-style reverb effect on the game's
// audio). On the Switch the audio thread runs it for ~0.5 s of every scene load and a large share of every frame's
// audio time, all under the GIL on core 0.
//
// Dissection (call graph of sub_827E2208(r3 = state, r4 = input channel pointers, r5 = output channel pointers),
// 256 samples per call, two input chains L and R):
//   827E0810  pre-delay: 16384-sample delay with a crossfade when the delay length changes
//   827E0EA8  two cascaded one-pole low-pass filters (damping)
//   827E0FD8  early-reflection taps on a 512-sample delay line (3 taps, 2 outputs)
//   827E10A8  all-pass diffuser, 128-sample delay (in place)
//   827E1330  reflection taps on a 2048-sample delay line
//   827E1400  all-pass diffuser, 256 (in place)        827E1728  all-pass diffuser, 512
//   827E1890  two-tap 1024-sample delay feeding the late reverb
//   main loop 1: early reflections = both chains mixed with 4 coefficients x reflections gain (8 signals)
//   main loop 2: late reverb, per sample, feedback delay network
//   827E15C0 x4, 827E1BF8 x2: output filters, then the mix into the 4 output channels.
// Every stage keeps the 360 convention of 257-entry buffers (entry 0 = the previous block's last sample).
//
// The native code (native_reverb_gen.inc) is generated by tools/gen_native_reverb.py from the original
// instructions with the recompiled code's exact arithmetic, so its output is bit-identical to the guest's; it is
// faster because registers are locals, memory is not volatile and the 17 KB stack frame is a native buffer.
//
// LSWTCS_REVERB (default 1 = native code): 0 = the guest code.
// LSWTCS_REVERBOFF (default 1, with the native code): run it off the guest scheduler's rotation (lswtcs_gil_blocking_urgent),
//   so other guest threads run while it computes, as they did next to the 360's audio hardware thread; on the
//   Switch the calling thread also moves to core 2 for the call (lsw_offcore_begin/end, platform_switch.cpp), since
//   every guest thread shares core 0. The reverb reads and writes only its own state, its inputs and outputs, and
//   the audio thread keeps whatever guest locks it holds, so the output is the same. Needs LSWTCS_IRQLFIX
//   (kernel_stubs.cpp) to get the turn back quickly. Eden hub 2026-10-11, back to back: p50/p90 23.9/28.1 ms ->
//   21.4/25.0 ms, audio thread on core 0 17.1 % -> 5.2 %, underruns unchanged. =0: native, in turn.
// LSWTCS_REVERBTRACE=1 (diagnostic): log which guest memory the reverb reads and writes ([REVERB] ranges).
// LSWTCS_REVERBCHECK=1 (diagnostic): the guest runs as usual; the native code runs on a shadow copy of the reverb
//   state with the same input; outputs are compared every block ([REVERB] MISMATCH). LSWTCS_REVERBWAV=N also
//   records N seconds of input and both outputs to sdmc:/lswtcs/reverb_{input,guest,native}.wav plus a native
//   impulse response reverb_native_ir.wav.
